def species_tag(name):
    return name.replace(
        "Enterobacter ", "E_"
    ).replace(" ", "_")


def class_rank(name):
    return CLASS_ORDER.index(name)


def get_species_data(species):

    sub = df[
        df["Species"] == species
    ].copy()

    if sub.empty:
        raise ValueError(
            f"No prevalence records for {species}"
        )

    inventory = sub[
        ["Gene", "AMR_Class"]
    ].drop_duplicates()

    # Sort gene groups by annotated class.
    inventory["Rank"] = (
        inventory["AMR_Class"]
        .apply(class_rank)
    )

    # More widespread genes shown first within class.
    max_prev = (
        sub.groupby("Gene")[
            "Prevalence_Percent"
        ].max()
    )

    inventory["Max_Prevalence"] = (
        inventory["Gene"]
        .map(max_prev)
    )

    inventory = inventory.sort_values(
        [
            "Rank",
            "Max_Prevalence",
            "Gene"
        ],
        ascending=[
            True,
            False,
            True
        ]
    ).reset_index(drop=True)

    genes = inventory["Gene"].tolist()
    classes = inventory["AMR_Class"].tolist()

    columns = [
        (source, inc)
        for source in SOURCES
        for inc in INCOMES
    ]

    pivot = sub.pivot(
        index="Gene",
        columns=[
            "Source",
            "Income"
        ],
        values="Prevalence_Percent"
    )

    pivot = pivot.reindex(
        index=genes,
        columns=pd.MultiIndex.from_tuples(columns)
    )

    matrix = pivot.to_numpy(
        dtype=np.float32
    )

    if len(genes) == 0:
        raise ValueError("No genes for " + species)

    if matrix.shape != (len(genes), 9):
        raise RuntimeError("Incorrect matrix dimensions")

    return genes, classes, matrix


def draw_species(species, figure_number):

    genes, classes, matrix = get_species_data(
        species
    )

    n = len(genes)

    # --------------------------------------------------------
    # Adaptive large-format figure.
    #
    # Each gene gets approximately 0.14 inches,
    # supporting ~9.5-point row labels.
    #
    # Narrow canvas controls total pixel count while
    # keeping every gene in one heatmap.
    # --------------------------------------------------------

    FIG_WIDTH = 7.35

    ROW_HEIGHT = 0.140
    TOP_MARGIN = 1.85
    BOTTOM_MARGIN = 1.75

    heat_height = n * ROW_HEIGHT

    FIG_HEIGHT = (
        TOP_MARGIN
        + heat_height
        + BOTTOM_MARGIN
    )

    pixel_count = (
        FIG_WIDTH * DPI
        * FIG_HEIGHT * DPI
    )

    print(
        f"\n{species}",
        flush=True
    )

    print(
        f"Genes: {n} | "
        f"Canvas: {FIG_WIDTH:.2f} x "
        f"{FIG_HEIGHT:.2f} inches | "
        f"Pixels: {pixel_count/1e6:.1f} million",
        flush=True
    )

    # These large images can still need substantial RAM.
    # Fail before rendering if an unexpected inventory
    # would result in more than 180 million pixels.
    if pixel_count > 180_000_000:
        raise MemoryError(
            f"Figure exceeds 180 million pixels: {species}. "
            "A wider/taller raster may require "
            "an alternative publication layout."
        )

    fig = plt.figure(
        figsize=(
            FIG_WIDTH,
            FIG_HEIGHT
        ),
        facecolor="white"
    )

    # Axes in inches converted to figure fractions.
    # Separate gene-label, AMR-class and heatmap axes.

    bottom = BOTTOM_MARGIN / FIG_HEIGHT
    height = heat_height / FIG_HEIGHT

    ax_names = fig.add_axes([
        0.015,
        bottom,
        0.292,
        height
    ])

    ax_class = fig.add_axes([
        0.311,
        bottom,
        0.022,
        height
    ])

    ax_heat = fig.add_axes([
        0.348,
        bottom,
        0.632,
        height
    ])

    for axis in [ax_names, ax_class]:

        axis.set_xlim(0, 1)
        axis.set_ylim(n-.5, -.5)
        axis.axis("off")

    image = ax_heat.imshow(
        np.ma.masked_invalid(matrix),
        cmap=CMAP,
        vmin=0,
        vmax=100,
        aspect="auto",
        interpolation="nearest",
        resample=False
    )

    ax_heat.set_xlim(-.5, 8.5)
    ax_heat.set_ylim(n-.5, -.5)

    ax_heat.set_xticks([])
    ax_heat.set_yticks([])

    for spine in ax_heat.spines.values():
        spine.set_visible(False)

    # --------------------------------------------------------
    # GENE LABELS
    # --------------------------------------------------------

    for i, gene in enumerate(genes):

        ax_names.text(
            0.985,
            i,
            gene,
            ha="right",
            va="center",
            fontsize=9.1,
            color="#172F4C"
        )

        cls = classes[i]

        ax_class.add_patch(
            Rectangle(
                (0, i-.5),
                1,
                1,
                facecolor=CLASS_COLORS[cls],
                edgecolor="none"
            )
        )

    # --------------------------------------------------------
    # CLASS BLOCK DIVIDERS
    # --------------------------------------------------------

    block_boundaries = [
        i
        for i in range(1, n)
        if classes[i] != classes[i-1]
    ]

    for boundary in block_boundaries:

        y = boundary - .5

        ax_heat.axhline(
            y,
            color="#53657B",
            linewidth=.60
        )

        ax_class.axhline(
            y,
            color="white",
            linewidth=.90
        )

    # Source-group separation.
    for x in [2.5, 5.5]:

        ax_heat.axvline(
            x,
            color="#FFFFFF",
            linewidth=1.2
        )

    # ========================================================
    # UPPER COLUMN STRIPS — DEDICATED AXES
    # ========================================================

    strip_height_inches = 0.48

    strip_bottom = (
        BOTTOM_MARGIN
        + heat_height
        + 0.11
    ) / FIG_HEIGHT

    ax_top = fig.add_axes([
        0.348,
        strip_bottom,
        0.632,
        strip_height_inches / FIG_HEIGHT
    ])

    ax_top.set_xlim(-.5, 8.5)
    ax_top.set_ylim(0, 2)
    ax_top.axis("off")

    for source_index, source in enumerate(SOURCES):

        start = source_index * 3

        # Source strip
        ax_top.add_patch(
            Rectangle(
                (start-.5, 1.02),
                3,
                .96,
                facecolor=SOURCE_COLORS[source],
                edgecolor="white",
                linewidth=.65
            )
        )

        ax_top.text(
            start+1,
            1.50,
            source,
            ha="center",
            va="center",
            fontsize=10.5,
            color="white",
            fontweight="bold"
        )

        for income_index, inc in enumerate(INCOMES):

            j = start + income_index

            ax_top.add_patch(
                Rectangle(
                    (j-.5, .02),
                    1,
                    .98,
                    facecolor=INCOME_COLORS[inc],
                    edgecolor="white",
                    linewidth=.40
                )
            )

            ax_top.text(
                j,
                .51,
                inc,
                ha="center",
                va="center",
                fontsize=8.8,
                fontweight="bold",
                color="white"
            )

    # ========================================================
    # TITLES
    # ========================================================

    fig.text(
        .50,
        1 - 0.44 / FIG_HEIGHT,
        species,
        ha="center",
        va="center",
        fontsize=15,
        fontstyle="italic",
        fontweight="bold",
        color="#142D50"
    )

    fig.text(
        .50,
        1 - 0.81 / FIG_HEIGHT,
        "AMR gene prevalence across One Health sources",
        ha="center",
        va="center",
        fontsize=10.0,
        color="#40546B"
    )

    fig.text(
        .16,
        strip_bottom + 0.59 / FIG_HEIGHT,
        "Individual AMR genes",
        ha="center",
        fontsize=9.1,
        fontweight="bold",
        color="#142D50"
    )

    fig.text(
        .32,
        strip_bottom + 0.59 / FIG_HEIGHT,
        "Class",
        ha="center",
        fontsize=8.6,
        fontweight="bold",
        color="#142D50"
    )

    # ========================================================
    # COLORBAR
    # ========================================================

    colorbar_y = 1.18 / FIG_HEIGHT

    cb_axis = fig.add_axes([
        .385,
        colorbar_y,
        .54,
        .105 / FIG_HEIGHT
    ])

    cb = fig.colorbar(
        image,
        cax=cb_axis,
        orientation="horizontal"
    )

    cb.set_ticks([
        0, 20, 40, 60, 80, 100
    ])

    cb.set_label(
        "Genomes carrying the gene (%)",
        fontsize=9,
        labelpad=4
    )

    cb.ax.tick_params(
        labelsize=8
    )

    # ========================================================
    # AMR CLASS LEGEND
    # ========================================================

    present_classes = [
        cls
        for cls in CLASS_ORDER
        if cls in set(classes)
    ]

    handles = [
        Patch(
            facecolor=CLASS_COLORS[cls],
            edgecolor="none",
            label=cls
        )
        for cls in present_classes
    ]

    # 4-column class legend
    fig.legend(
        handles=handles,
        loc="lower left",
        bbox_to_anchor=(
            .015,
            .22 / FIG_HEIGHT
        ),
        ncol=4,
        fontsize=7.2,
        frameon=False,
        columnspacing=.8,
        handlelength=1.15,
        handleheight=.85
    )

    fig.text(
        .5,
        .055 / FIG_HEIGHT,
        "Grey = no genomes in the corresponding "
        "species-source-income group. "
        "AMR classes require gene-level verification.",
        ha="center",
        va="bottom",
        fontsize=7.0,
        color="#5F6D7D"
    )

    # ========================================================
    # SAVE JPEG
    # ========================================================

    path = OUTPUT / (
        f"Fig04_{figure_number:02d}_"
        f"{species_tag(species)}"
        "_NATURE_STYLE.jpg"
    )

    fig.savefig(
        path,
        dpi=DPI,
        format="jpeg",
        facecolor="white",
        pil_kwargs={
            "quality": 90,
            "subsampling": 2,
            "optimize": False
        }
    )

    plt.close(fig)
    gc.collect()

    if not path.is_file():
        raise RuntimeError(
            "Figure file not created: "
            + str(path)
        )

    if path.stat().st_size < 10000:
        raise RuntimeError(
            "Figure file unexpectedly small: "
            + str(path)
        )

    # Size-only verification to avoid decoding another
    # huge image into memory.
    with Image.open(path) as im:

        dimensions = im.size
        fmt = im.format

    if fmt != "JPEG":
        raise RuntimeError("Output is not JPEG")

    expected_width = round(FIG_WIDTH * DPI)
    expected_height = round(FIG_HEIGHT * DPI)

    if (
        abs(dimensions[0] - expected_width) > 2
        or abs(dimensions[1] - expected_height) > 2
    ):
        raise RuntimeError(
            f"Unexpected image dimensions: {dimensions}"
        )

    print(
        "[SAVED]",
        path.name,
        "| pixels:",
        dimensions,
        "| MB:",
        round(path.stat().st_size / 1024**2, 1),
        flush=True
    )

    return path


